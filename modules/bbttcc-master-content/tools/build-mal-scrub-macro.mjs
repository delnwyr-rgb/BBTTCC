// Builds mal-scrub-item-glances-2026-11-12.macro.js (self-contained, paste into a GM console / macro on the live world).
import fs from "fs"; import path from "path"; import { fileURLToPath } from "url";
import { stripMal, dropMalVoicedLead, scrubItemUpdate } from "./strip-mal.mjs";
const here = path.dirname(fileURLToPath(import.meta.url));
const glances = fs.readFileSync(path.join(here, "item-glances-2026-11-12.json"), "utf8");
const mal = fs.readFileSync(path.join(here, "mal-voiced-items-2026-11-12.json"), "utf8");
const powers = fs.readFileSync(path.join(here, "canon-powers-2026-11-12.json"), "utf8");
const out = `/* mal-scrub-item-glances-2026-11-12.macro.js — GENERATED by build-mal-scrub-macro.mjs; edit strip-mal.mjs instead.
 * Dave 2026-11-12: "scrub our item content of Mal descriptions … clarity on functionality a priority over color".
 * For every weapon / armor / gear / power Item — master-content + system compendium packs (unlocked for the write, re-locked after), world
 * items, items embedded on world actors, items embedded on actors in master-content Actor packs:
 *   • strips Mal's asides (Mal: '…', (Mal: "…"), sentences naming Mal) from description, lore, flavor, bound-Working flavor;
 *   • canon powers (by name): system.flavor cleared — it is Mal's line by convention; player-made powers untouched;
 *   • Mal-voiced gear set: drops the leading colour paragraph(s), clears system.flavor — rule paragraphs stay;
 *   • writes flags.fourththing.rfi.item.glance (the inventory row's "what it does" line) for gear the engine can't compute.
 * Idempotent; DRY_RUN default true; GM only. Marker: [MAL-SCRUB-2026-11-12] */
(async () => {
  const DRY_RUN = true;   // <-- set false to apply
  if (!game.user?.isGM) return ui.notifications.error("GM only.");
  const GLANCES = ${glances.trim()};
  const MAL_NAMES = new Set(${mal.trim()});
  const CANON_POWERS = new Set(${powers.trim()});   // their flavor is Mal's line — cleared; player-made powers keep theirs
  ${stripMal.toString()}
  ${dropMalVoicedLead.toString()}
  ${scrubItemUpdate.toString()}
  const TYPES = new Set(["weapon", "armor", "gear", "power"]);   // powers too (Dave 11-12: "scrub those too")
  const isMalVoiced = (it) => MAL_NAMES.has(it.name) || (Array.isArray(it.system?.tags) && it.system.tags.some(t => /^mal[- ]voiced$/i.test(String(t))));
  const updFor = (it) => TYPES.has(it.type) ? scrubItemUpdate(it.toObject(), { malVoiced: isMalVoiced(it), clearFlavor: it.type === "power" && CANON_POWERS.has(it.name), glance: GLANCES[it.name] }) : null;
  const report = []; let changes = 0;
  const mine = (p) => ["bbttcc-master-content", "fourththing"].includes(p.metadata.packageName);
  const unlockedWrite = async (pack, fn) => { const was = pack.locked; if (was) await pack.configure({ locked: false }); try { await fn(); } finally { if (was) await pack.configure({ locked: true }); } };
  const doItems = async (items, where, opts = {}) => {
    const rows = []; for (const it of items) { const u = updFor(it); if (u) { rows.push({ _id: it.id, ...u }); report.push(\`\${where} · \${it.name}: \${Object.keys(u).map(k => k.split(".").at(-1)).join(", ")}\`); } }
    changes += rows.length; return rows;
  };
  for (const pack of game.packs.filter(p => mine(p) && p.documentName === "Item")) {
    const docs = await pack.getDocuments(); const rows = await doItems(docs, pack.metadata.label);
    if (rows.length && !DRY_RUN) await unlockedWrite(pack, () => Item.updateDocuments(rows, { pack: pack.collection }));
  }
  { const rows = await doItems(game.items, "world"); if (rows.length && !DRY_RUN) await Item.updateDocuments(rows); }
  for (const a of game.actors) { const rows = await doItems(a.items, \`actor \${a.name}\`); if (rows.length && !DRY_RUN) await a.updateEmbeddedDocuments("Item", rows); }
  for (const pack of game.packs.filter(p => mine(p) && p.documentName === "Actor")) {
    const docs = await pack.getDocuments();
    for (const a of docs) { const rows = await doItems(a.items, \`\${pack.metadata.label} › \${a.name}\`); if (rows.length && !DRY_RUN) await unlockedWrite(pack, () => a.updateEmbeddedDocuments("Item", rows)); }
  }
  console.log("[MAL-SCRUB-2026-11-12]", DRY_RUN ? "DRY RUN" : "APPLIED", changes, "item updates\\n" + report.join("\\n"));
  ui.notifications.info(\`Mal scrub: \${changes} item updates \${DRY_RUN ? "(dry run — set DRY_RUN = false)" : "applied"}.\`);
  return { dryRun: DRY_RUN, changes, report };
})();
`;
fs.writeFileSync(path.join(here, "mal-scrub-item-glances-2026-11-12.macro.js"), out);
console.log("wrote", out.length);
